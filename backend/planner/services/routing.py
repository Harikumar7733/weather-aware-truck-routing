"""Route options from OSRM.

OSRM's ``alternatives`` parameter often returns fewer than three routes, so the
remaining options are generated by forcing a via-point offset to either side of
the straight line between origin and destination. Candidates that mostly
overlap an existing route, or are unreasonably long, are discarded.
"""

from __future__ import annotations

import logging
from concurrent.futures import ThreadPoolExecutor

from django.conf import settings
from django.core.cache import cache

from ..domain.geo import LatLon, destination_point, haversine_mi, initial_bearing, sample_every
from ..domain.route import Route
from .http import UpstreamError, ValidationError, get_json

logger = logging.getLogger(__name__)

TARGET_ROUTES = 3
OVERLAP_RADIUS_MI = 1.5
VIA_OFFSETS = (0.18, -0.18, 0.35, -0.35, 0.55, -0.55)  # fraction of the straight-line distance
# (max duration vs fastest, max share overlapping an existing route). The relaxed pass
# only runs when the strict one cannot produce three options (e.g. sparse mountain networks).
STRICT = (1.6, 0.8)
RELAXED = (2.2, 0.93)


def _osrm(points: list[LatLon], alternatives: bool) -> list[dict]:
    coords = ";".join(f"{lon:.6f},{lat:.6f}" for lat, lon in points)
    key = f"osrm:{coords}:{alternatives}"
    if (cached := cache.get(key)) is not None:
        return cached
    data = get_json(
        f"{settings.OSRM_URL}/route/v1/driving/{coords}",
        {
            "alternatives": "3" if alternatives else "false",
            "overview": "full",
            "geometries": "geojson",
            "annotations": "duration",
            "steps": "true",
        },
        service="Routing service",
        timeout=30,
    )
    if data.get("code") != "Ok":
        if data.get("code") in {"NoRoute", "NoSegment"}:
            raise ValidationError("No drivable route was found between these locations.")
        raise UpstreamError(f"Routing service error: {data.get('message') or data.get('code')}")
    routes = data.get("routes", [])
    cache.set(key, routes, 6 * 3600)
    return routes


def _summary(raw: dict) -> str:
    names: list[str] = []
    for leg in raw.get("legs", []):
        for name in (leg.get("summary") or "").split(", "):
            if name and name not in names:
                names.append(name)
    return ", ".join(names[:3])


def _to_route(raw: dict) -> Route:
    coords = [(lat, lon) for lon, lat in raw["geometry"]["coordinates"]]
    durations: list[float] = []
    for leg in raw.get("legs", []):
        durations.extend(leg.get("annotation", {}).get("duration", []))
    return Route.build(
        coords,
        total_duration_s=raw["duration"],
        segment_durations_s=durations or None,
        max_speed_mph=settings.TRUCK_MAX_SPEED_MPH,
        summary=_summary(raw),
    )


def _overlap(candidate: Route, existing: Route) -> float:
    """Share of the candidate's sampled points lying within OVERLAP_RADIUS_MI of ``existing``."""
    probe = sample_every(candidate.coords, candidate.miles, max(candidate.distance_mi / 40, 1))
    ref = sample_every(existing.coords, existing.miles, 0.75)
    hits = sum(1 for p in probe if any(haversine_mi(p, q) <= OVERLAP_RADIUS_MI for q in ref))
    return hits / len(probe)


def _is_distinct(candidate: Route, chosen: list[Route], limits: tuple[float, float] = STRICT) -> bool:
    max_ratio, max_overlap = limits
    fastest = min(r.drive_duration_s for r in chosen)
    if candidate.drive_duration_s > fastest * max_ratio:
        return False
    return all(_overlap(candidate, r) < max_overlap for r in chosen)


def _via_points(origin: LatLon, destination: LatLon) -> list[LatLon]:
    span = haversine_mi(origin, destination)
    mid = ((origin[0] + destination[0]) / 2, (origin[1] + destination[1]) / 2)
    bearing = initial_bearing(origin, destination)
    return [destination_point(mid, bearing + (90 if f > 0 else -90), abs(f) * span) for f in VIA_OFFSETS]


def _via_route(origin: LatLon, via: LatLon, destination: LatLon) -> Route | None:
    try:
        raw = _osrm([origin, via, destination], alternatives=False)
        return _to_route(raw[0]) if raw else None
    except (UpstreamError, ValidationError) as exc:
        logger.info("via route through %s rejected: %s", via, exc)
        return None


def route_options(origin: LatLon, destination: LatLon) -> list[Route]:
    """Up to three distinct routes, fastest first.

    Via-point candidates are requested in parallel with the main query (OSRM rarely
    returns three alternatives), and only used when the main query falls short.
    """
    if haversine_mi(origin, destination) < 1:
        raise ValidationError("Origin and destination are too close together.")
    vias = _via_points(origin, destination)
    with ThreadPoolExecutor(max_workers=1 + len(vias)) as pool:
        main = pool.submit(_osrm, [origin, destination], True)
        via_futures = [pool.submit(_via_route, origin, via, destination) for via in vias]
        routes = [_to_route(r) for r in main.result()]
        if not routes:
            raise ValidationError("No drivable route was found between these locations.")
        chosen: list[Route] = []
        for route in routes:
            if not chosen or _is_distinct(route, chosen):
                chosen.append(route)
        candidates = [c for c in (f.result() for f in via_futures) if c is not None]

    for limits in (STRICT, RELAXED):
        for candidate in candidates:
            if len(chosen) >= TARGET_ROUTES:
                break
            if all(candidate is not c for c in chosen) and _is_distinct(candidate, chosen, limits):
                chosen.append(candidate)

    chosen.sort(key=lambda r: r.drive_duration_s)
    return chosen[:TARGET_ROUTES]
